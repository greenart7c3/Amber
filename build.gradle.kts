subprojects {
    // `src` covers every source set, including the app's flavor directories.
    plugins.withId("dev.detekt") {
        // One baseline per module, shared by every variant and source set:
        // detekt would otherwise suffix the name with the variant
        // (detekt-baseline-freeDebug.xml) and copy the same violations into each
        // file. Existing violations of the complexity and Compose rules are
        // grandfathered; new code is checked. Never add an entry by hand: split
        // the code instead. Regenerate with `./gradlew detektBaselineAll`, which
        // merges each task's findings into the module's file (see below).
        val baselineFile = project.layout.projectDirectory.file("detekt-baseline.xml")
        extensions.configure<dev.detekt.gradle.extensions.DetektExtension> {
            source.setFrom("src")
            baseline.set(baselineFile)
            // The Compose rules (config/detekt/compose.yml) are only on the
            // detekt classpath of the modules that declare them, and detekt
            // rejects their ruleset key in the others.
            if (project.path in composeDetektModules) {
                config.setFrom(
                    rootProject.file("config/detekt/detekt.yml"),
                    rootProject.file("config/detekt/compose.yml"),
                )
            }
        }
        tasks.withType<Detekt>().configureEach { baseline.set(baselineFile) }
        // detekt writes a baseline from scratch (it does not merge), so each
        // baseline task gets its own file under build/, and detektBaselineAll
        // unions them into the committed one.
        tasks.withType<DetektCreateBaselineTask>().configureEach {
            baseline.set(project.layout.buildDirectory.file("detekt-baselines/${name}.xml"))
        }
    }

    tasks.withType<KotlinCompile>().configureEach {
        compilerOptions {
            // Deprecations, needless null checks, unused expressions and the like
            // fail the build; suppress one at its site when it is deliberate.
            allWarningsAsErrors.set(true)
            val buildDirPath = project.layout.buildDirectory.get().asFile.absolutePath
            if (project.findProperty("composeCompilerReports") == "true") {
                freeCompilerArgs.addAll(
                    "-P",
                    "plugin:androidx.compose.compiler.plugins.kotlin:reportsDestination=" +
                        buildDirPath + "/compose_compiler",
                )
            }
            if (project.findProperty("composeCompilerMetrics") == "true") {
                freeCompilerArgs.addAll(
                    "-P",
                    "plugin:androidx.compose.compiler.plugins.kotlin:metricsDestination=" +
                        buildDirPath + "/compose_compiler",
                )
            }
        }
    }
}

// Coverage: one merged report for every module (see the kover(project(...))
// dependencies above). Generated code is excluded; the minimum coverage bound
// for :common lives in common/build.gradle.kts, so it is checked against that
// module alone (`:common:koverVerify`).
kover {
    reports {
        filters {
            excludes {
                // R, BuildConfig, Manifest and friends.
                androidGeneratedClasses()
                // Room, Compose and the Compose resources plugin generate these.
                classes(
                    "*_Impl",
                    "*_Impl\$*",
                    "*BuildConfig*",
                    "*ComposableSingletons*",
                    "*Preview*",
                    "com.greenart7c3.nostrsigner.commonsui.Res*",
                )
            }
        }
        total {
            html {
                // Coverage is reported and verified in CI, not on every `check`.
                onCheck = false
            }
            xml {
                onCheck = false
            }
        }
    }
}
