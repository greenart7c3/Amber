// Regenerates the per-module detekt-baseline.xml files. detekt's baseline tasks
// write a file from scratch (they do not merge), so each of them writes under
// build/detekt-baselines/ and this unions and sorts all of them into the
// module's committed file. Entries for code that no longer violates disappear,
// so a regenerated baseline only shrinks.
tasks.register("detektBaselineAll") {
    group = "verification"
    description = "Regenerates the detekt baselines of every module and source set."
    dependsOn(
        ":app:detektBaselineFreeDebug",
        ":app:detektBaselineOfflineDebug",
        ":app:detektBaselineFreeDebugUnitTest",
        ":app:detektBaselineOfflineDebugUnitTest",
        ":app:detektBaselineFreeDebugAndroidTest",
        ":app:detektBaselineOfflineDebugAndroidTest",
        ":cli:detektBaselineMain",
        ":cli:detektBaselineTest",
        ":common:detektBaselineMain",
        ":common:detektBaselineTest",
        ":commonsui:detektBaselineMainJvm",
        ":commonsui:detektBaselineMainAndroid",
        ":commonsui:detektBaselineTestJvm",
        ":desktop:detektBaselineMain",
        ":desktop:detektBaselineTest",
        ":architecture-tests:detektBaselineMain",
        ":architecture-tests:detektBaselineTest",
        ":unused-code:detektBaselineMain",
        ":unused-code:detektBaselineTest",
    )

    val modules = listOf(
        ":app" to "app",
        ":cli" to "cli",
        ":common" to "common",
        ":commonsui" to "commonsui",
        ":desktop" to "desktop",
        ":architecture-tests" to "tools/architecture-tests",
        ":unused-code" to "tools/unused-code",
    )
    val taskBaselines = modules.map { (path, _) ->
        project(path).layout.buildDirectory.dir("detekt-baselines").get().asFile
    }
    val moduleBaselines = modules.map { (_, dir) -> File(rootDir, "$dir/detekt-baseline.xml") }
    inputs.files(taskBaselines).withPropertyName("taskBaselines")
    outputs.files(moduleBaselines).withPropertyName("moduleBaselines")

    doLast {
        val idPattern = Regex("<ID>(.*?)</ID>", RegexOption.DOT_MATCHES_ALL)
        modules.indices.forEach { index ->
            val taskDir = taskBaselines[index]
            val current = sortedSetOf<String>()
            val suppressed = sortedSetOf<String>()
            taskDir.listFiles { entry -> entry.isFile && entry.extension == "xml" }
                ?.sortedBy { it.name }
                ?.forEach { baselineTaskFile ->
                    val text = baselineTaskFile.readText()
                    idPattern.findAll(text).forEach { current += it.groupValues[1] }
                    // ManuallySuppressedIssues precedes CurrentIssues in the file.
                    val manual = text.substringAfter("<ManuallySuppressedIssues>", "")
                        .substringBefore("</ManuallySuppressedIssues>", "")
                    idPattern.findAll(manual).forEach { suppressed += it.groupValues[1] }
                }
            val out = moduleBaselines[index]
            out.parentFile.mkdirs()
            out.writeText(
                buildString {
                    append("<?xml version=\"1.0\" ?>\n")
                    append("<SmellBaseline>\n")
                    if (suppressed.isEmpty()) {
                        append("  <ManuallySuppressedIssues/>\n")
                    } else {
                        append("  <ManuallySuppressedIssues>\n")
                        suppressed.forEach { append("    <ID>$it</ID>\n") }
                        append("  </ManuallySuppressedIssues>\n")
                    }
                    append("  <CurrentIssues>\n")
                    current.forEach { append("    <ID>$it</ID>\n") }
                    append("  </CurrentIssues>\n")
                    append("</SmellBaseline>\n")
                },
            )
        }
    }
}

